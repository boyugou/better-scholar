"use strict";
// AGENTS.md: the reference for AI agents, generated from src/lib/agent.js (the same text the settings page copies), with the rules for working on this
// repository. `npm run agents:doc` writes it; test/agents-doc.test.js fails when the committed file is stale.
const fs = require("node:fs");
const path = require("node:path");

const repo = path.join(__dirname, "..");
const agent = require(path.join(repo, "src/lib/agent.js"));
const manifest = JSON.parse(fs.readFileSync(path.join(repo, "src/manifest.json"), "utf8"));

const RULES = [
  "## Rules for working on this repository",
  "",
  "- Chrome first (Manifest V3). No build step and no runtime dependency: `src/` is loaded unpacked.",
  "- `src/lib/` is pure: no DOM and no `chrome.*`. It is unit-tested in Node (`npm test`).",
  "- Precision over recall in venue matching: a missing badge is fine, a wrong one is not.",
  "- Privacy: no network request of the extension's own, except the user-triggered reads of Scholar pages and the opt-in Semantic Scholar title lookup. No analytics, no remote code.",
  "- Every user-visible string is in all 30 `src/_locales/*/messages.json` files (tested). A setting is a row of `SETTINGS` in `src/lib/prefs.js`.",
  "- Everything the extension adds to a Scholar page is prefixed `rr-`.",
  "- Do not name competitors or other extensions in code, tests, commits or documentation.",
  "- Commands: `npm test`, `npm run test:e2e` (Chromium against the stand-in Scholar server), `npm run data`, `npm run agents:doc` (regenerates this file).",
  "",
];

function render() {
  const guide = agent.guide({ version: manifest.version });
  return ["<!-- Generated by `npm run agents:doc` from src/lib/agent.js. Edit that file, not this one. -->", "", guide.trimEnd(), "", ...RULES].join("\n") + "\n";
}

if (require.main === module) fs.writeFileSync(path.join(repo, "AGENTS.md"), render());
module.exports = { render };
